def check_primary_index(df_name, df, candidate_keys):
    if df is None:
        print(f"{df_name}: Dataset not loaded.")
        return

    print(f"=== Checking Primary Index Candidates for {df_name} ===")
    total_rows = len(df)
    print(f"Total Rows: {total_rows}")

    for keys in candidate_keys:
        # Ensure all columns in key candidates exist in the dataframe
        existing_keys = [k for k in keys if k in df.columns]
        if len(existing_keys) != len(keys):
            continue

        # Drop rows with nulls in key columns for uniqueness testing
        non_null_df = df.dropna(subset=keys)
        unique_count = len(non_null_df.groupby(keys))
        has_nulls = df[keys].isnull().any().any()

        print(f" - Grouping by {keys}:")
        print(f"   * Non-null unique groups: {unique_count}")
        print(f"   * Total rows (without nulls in key): {len(non_null_df)}")
        if unique_count == total_rows and not has_nulls:
            print(f"   * VALID PRIMARY INDEX: Yes (Uniquely identifies 100% of rows with zero missing values).")
        elif unique_count == len(non_null_df):
            print(f"   * VALID PRIMARY INDEX: Yes, when excluding rows with missing values.")
        else:
            print(f"   * VALID PRIMARY INDEX: No (Contains duplicate combinations).")
    print()

