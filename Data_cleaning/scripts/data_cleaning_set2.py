if 'covid_df' in locals() and covid_df is not None:
    print(f"Initial nulls in covid_df: {covid_df.isnull().sum().sum()}")

    # Ensure date is sorted sequentially per country for reliable rolling/ffill actions
    covid_df = covid_df.sort_values(by=['isocode', 'date']).reset_index(drop=True)

    # Grouped cumulative fields forward-fill then fill left-over NaNs with 0
    cum_cols = [c for c in ['totalcases', 'totaldeaths', 'totalcasespermillion', 'totaldeathspermillion'] if c in covid_df.columns]
    for col in cum_cols:
        covid_df[col] = covid_df.groupby('isocode')[col].ffill().fillna(0)

    # Daily flow metrics filled with 0
    flow_cols = [c for c in ['newcases', 'newdeaths', 'newcasespermillion', 'newdeathspermillion'] if c in covid_df.columns]
    for col in flow_cols:
        covid_df[col] = covid_df[col].fillna(0)

    # Static country indicators backfilled / forward-filled within country, or regional backup
    static_cols = [c for c in ['population', 'gdppercapita', 'populationdensity', 'medianage', 'aged65older', 'lifeexpectancy', 'humandevelopmentindex'] if c in covid_df.columns]
    for col in static_cols:
        covid_df[col] = covid_df.groupby('isocode')[col].ffill().bfill()
        # If any global nulls remain for country codes lacking indicators entirely, fill with global median
        if covid_df[col].isnull().any():
            covid_df[col] = covid_df[col].fillna(covid_df[col].median())

    # For any remaining columns, we'll perform a generic forward-fill/backward-fill within country first
    other_cols = [c for c in covid_df.columns if c not in cum_cols + flow_cols + static_cols + ['isocode', 'date', 'countryname', 'continent']]
    for col in other_cols:
        covid_df[col] = covid_df.groupby('isocode')[col].ffill().bfill()
        # Final catch-all fill with 0 if no values exist for a country
        covid_df[col] = covid_df[col].fillna(0)

    print(f"Remaining nulls in covid_df: {covid_df.isnull().sum().sum()}")

