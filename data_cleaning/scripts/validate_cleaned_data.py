#!/usr/bin/env python3
"""Validate cleaned outputs and generate a human-readable quality report."""

import csv
import hashlib
from collections import Counter
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[1]
RAW = PROJECT_ROOT / "data" / "raw"
INTERIM = PROJECT_ROOT / "data" / "interim"
PROCESSED = PROJECT_ROOT / "data" / "processed"
REPORT_PATH = PROJECT_ROOT / "reports" / "cleaning_validation.md"

RAW_FILES = [
    RAW / "oxcgrt" / "OxCGRT_compact_national_v1.csv",
    RAW / "google_mobility" / "mobility.csv",
    RAW / "google_mobility" / "index.csv",
    RAW / "world_bank" / "countries.json",
]


def read_csv(path: Path) -> tuple[list[str], list[dict[str, str]]]:
    with path.open(newline="", encoding="utf-8-sig") as source:
        reader = csv.DictReader(source)
        return list(reader.fieldnames or []), list(reader)


def assert_unique(rows: list[dict[str, str]], fields: list[str], label: str) -> None:
    counts = Counter(tuple(row[field] for field in fields) for row in rows)
    duplicates = [key for key, count in counts.items() if count > 1]
    if duplicates:
        raise ValueError(f"{label} has duplicate keys: {duplicates[:5]}")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def missing_table(
    rows: list[dict[str, str]], fields: list[str]
) -> list[tuple[str, int, float]]:
    results = []
    for field in fields:
        missing = sum(row.get(field, "") == "" for row in rows)
        percentage = missing / len(rows) * 100 if rows else 0
        results.append((field, missing, percentage))
    return results


def main() -> None:
    metadata_fields, metadata = read_csv(PROCESSED / "country_metadata_clean.csv")
    ox_daily_fields, ox_daily = read_csv(INTERIM / "oxcgrt_country_day_clean.csv")
    ox_annual_fields, ox_annual = read_csv(PROCESSED / "oxcgrt_country_year_clean.csv")
    mobility_daily_fields, mobility_daily = read_csv(
        INTERIM / "google_mobility_country_day_clean.csv"
    )
    mobility_annual_fields, mobility_annual = read_csv(
        PROCESSED / "google_mobility_country_year_clean.csv"
    )
    merged_fields, merged = read_csv(PROCESSED / "merged_country_year_clean.csv")

    assert_unique(metadata, ["iso_code"], "World Bank metadata")
    assert_unique(ox_daily, ["iso_code", "date"], "OxCGRT daily")
    assert_unique(ox_annual, ["iso_code", "year"], "OxCGRT annual")
    assert_unique(mobility_daily, ["iso_code", "date"], "Mobility daily")
    assert_unique(mobility_annual, ["iso_code", "year"], "Mobility annual")
    assert_unique(merged, ["iso_code", "year"], "Merged dataset")

    metadata_codes = {row["iso_code"] for row in metadata}
    policy_codes = {row["iso_code"] for row in ox_annual}
    mobility_codes = {row["iso_code"] for row in mobility_annual}
    policy_missing_metadata = sorted(policy_codes - metadata_codes)
    mobility_missing_metadata = sorted(mobility_codes - metadata_codes)

    policy_value_fields = [
        field for field in ox_daily_fields if field not in {"country", "iso_code", "date", "year"}
    ]
    mobility_value_fields = [
        field
        for field in mobility_daily_fields
        if field not in {"country", "iso_code", "iso2_code", "date", "year"}
    ]

    lines = [
        "# Cleaning Validation Report",
        "",
        "This report is generated by `scripts/validate_cleaned_data.py`.",
        "",
        "## Stage counts",
        "",
        "| Dataset | Stage | Rows | Columns |",
        "|---|---|---:|---:|",
        f"| World Bank metadata | Processed | {len(metadata):,} | {len(metadata_fields)} |",
        f"| OxCGRT | Clean country-day | {len(ox_daily):,} | {len(ox_daily_fields)} |",
        f"| OxCGRT | Country-year | {len(ox_annual):,} | {len(ox_annual_fields)} |",
        f"| Google Mobility | Clean country-day | {len(mobility_daily):,} | {len(mobility_daily_fields)} |",
        f"| Google Mobility | Country-year | {len(mobility_annual):,} | {len(mobility_annual_fields)} |",
        f"| Combined (merged) | Country-year | {len(merged):,} | {len(merged_fields)} |",
        "",
        "## Uniqueness checks",
        "",
        "All expected primary keys are unique:",
        "",
        "- Metadata: `iso_code`",
        "- Daily datasets: `iso_code + date`",
        "- Annual and merged datasets: `iso_code + year`",
        "",
        "## Country-code matching",
        "",
        f"- OxCGRT ISO-3 codes absent from World Bank metadata: {policy_missing_metadata or 'None'}",
        f"- Mobility ISO-3 codes absent from World Bank metadata: {mobility_missing_metadata or 'None'}",
        "",
        "These records are retained rather than silently discarded.",
        "",
        "## Missing values in clean daily OxCGRT fields",
        "",
        "| Field | Missing | Missing % |",
        "|---|---:|---:|",
    ]
    for field, missing, percentage in missing_table(ox_daily, policy_value_fields):
        lines.append(f"| `{field}` | {missing:,} | {percentage:.2f}% |")

    lines.extend(
        [
            "",
            "## Missing values in clean daily mobility fields",
            "",
            "| Field | Missing | Missing % |",
            "|---|---:|---:|",
        ]
    )
    for field, missing, percentage in missing_table(
        mobility_daily, mobility_value_fields
    ):
        lines.append(f"| `{field}` | {missing:,} | {percentage:.2f}% |")

    lines.extend(["", "## Raw-file fingerprints", ""])
    for path in RAW_FILES:
        lines.append(f"- `{path.relative_to(PROJECT_ROOT)}`: `{sha256(path)}`")

    lines.extend(
        [
            "",
            "## Validation result",
            "",
            "**PASS** - no duplicate primary keys were found and every output was read successfully.",
            "",
        ]
    )

    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Validation passed")
    print(f"Report: {REPORT_PATH}")


if __name__ == "__main__":
    main()
